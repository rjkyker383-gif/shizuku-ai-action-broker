package com.rjkyker.shizukuai.broker.stagenow

/**
 * StageNow / MX CSP XML templates (wap-provisioningdoc). Pure Kotlin.
 * These are the legitimate, documented MX characteristics that StageNow can apply.
 * Premium / licensed MX features are NOT generated here — see [omittedLicensed].
 */
object StageNowXml {
    data class Profile(val name: String, val xml: String, val needsLicense: Boolean, val note: String)

    fun wrap(body: String) = """
        |<!-- Generated by Shizuku AI Broker. Apply via StageNow (Workstation → Xpert mode → XML) or share into the StageNow app. -->
        |<wap-provisioningdoc>
        |$body
        |</wap-provisioningdoc>
    """.trimMargin()

    /** AccessMgr: System Settings = Full (1). Classic unlock when OSX Provision Service locked Settings. */
    fun accessMgrFullSettings() = Profile(
        "AccessMgr_Full_Settings",
        wrap("""  <characteristic type="AccessMgr" version="4.1">
    <parm name="SystemSettings" value="1"/>
  </characteristic>"""),
        needsLicense = false,
        note = "MX AccessMgr SystemSettings=Full. Works without Mobility DNA license on devices that accept AccessMgr.",
    )

    fun settingsMgrEnables() = Profile(
        "SettingsMgr_Enable_Common",
        wrap("""  <characteristic type="SettingsMgr" version="4.3">
    <parm name="WifiSettingsUI" value="1"/>
    <parm name="AccessAppsSection" value="1"/>
    <parm name="AirplaneMode" value="1"/>
    <parm name="TetheringandPortableHotspot" value="1"/>
  </characteristic>"""),
        needsLicense = false,
        note = "Re-enables common Settings panes. May be ignored if AccessMgr still locks the UI.",
    )

    /** AppMgr disable-user for a package (e.g. OSX Provision Service). High impact; owner must confirm. */
    fun appMgrDisable(pkg: String): Profile {
        require(pkg.matches(Regex("""[a-zA-Z0-9._]+"""))) { "bad package" }
        return Profile(
            "AppMgr_Disable_$pkg",
            wrap("""  <characteristic type="AppMgr" version="5.1">
    <parm name="Action" value="DisableApplication"/>
    <parm name="Package" value="$pkg"/>
  </characteristic>"""),
            needsLicense = false,
            note = "AppMgr DisableApplication for $pkg. Prefer after Settings are unlocked. Not a wipe.",
        )
    }

    fun wifiMgrAddOpen(ssid: String): Profile {
        require(ssid.isNotBlank() && ssid.length <= 32) { "bad ssid" }
        val esc = ssid.replace("&", "&amp;").replace("<", "&lt;").replace("\"", "&quot;")
        return Profile(
            "WiFi_Add_Open",
            wrap("""  <characteristic type="Wi-Fi" version="4.4">
    <parm name="NetworkAction" value="Add"/>
    <characteristic type="network-details">
      <parm name="SSID" value="$esc"/>
      <parm name="SecurityMode" value="0"/>
    </characteristic>
  </characteristic>"""),
            needsLicense = false,
            note = "Basic open Wi-Fi Add via MX Wi-Fi CSP. Advanced Fusion / 802.11r-k-v needs a DNA license and is not generated.",
        )
    }

    fun combinedUnlock() = Profile(
        "UNLOCK_COMBINED",
        wrap("""  <characteristic type="AccessMgr" version="4.1">
    <parm name="SystemSettings" value="1"/>
  </characteristic>
  <characteristic type="SettingsMgr" version="4.3">
    <parm name="WifiSettingsUI" value="1"/>
    <parm name="AccessAppsSection" value="1"/>
    <parm name="AirplaneMode" value="1"/>
    <parm name="TetheringandPortableHotspot" value="1"/>
  </characteristic>"""),
        needsLicense = false,
        note = "AccessMgr Full + SettingsMgr enables. Same shape as the known StageNow unlock pack. No DevAdmin Turn-Off is included by default (owner must pick a target).",
    )

    fun catalog(): List<Profile> = listOf(
        accessMgrFullSettings(), settingsMgrEnables(), combinedUnlock(),
        appMgrDisable("com.symbol.osx.osxprovisionservice"),
    )

    val omittedLicensed = listOf(
        "OEMConfig premium / advanced MX feature tiers",
        "Premium StageNow profiles that require a Mobility DNA entitlement",
        "Fusion Advanced Wi-Fi (802.11r/k/v tuning, band lock, CCKM)",
        "Enterprise Browser / Enterprise Keyboard premium",
        "Any forged or reflected Mobility DNA / MX license key",
    )
}
